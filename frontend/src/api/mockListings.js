// Filter by location string (case-insensitive partial match)
export function getMockListings(location = "") {
  if (!location) return MOCK_LISTINGS;
  const q = location.toLowerCase();
  const filtered = MOCK_LISTINGS.filter(
    (l) => l.location.toLowerCase().includes(q) || l.title.toLowerCase().includes(q)
  );
  // If nothing matches the specific city, return all so the page is never empty
  return filtered.length > 0 ? filtered : MOCK_LISTINGS;
}
